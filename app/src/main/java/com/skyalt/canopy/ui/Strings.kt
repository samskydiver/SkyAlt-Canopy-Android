        val pattern = invoke(key)
            .replace(Regex("%(\\d)\\\$@")) { "%" + it.groupValues[1] + "\$s" }
            .replace("%@", "%s")
            .replace(Regex("%(\\d\\\$)?lld")) { "%" + it.groupValues[1] + "d" }
            .replace(Regex("%(\\d\\\$)?ld")) { "%" + it.groupValues[1] + "d" }
        return String.format(Locale.US, pattern, *args)
    }

